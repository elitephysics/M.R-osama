-- Profiles
 drop policy if exists "profiles own read" on public.profiles;
 create policy "profiles own read" on public.profiles for select using(auth.uid()=id or public.is_teacher());
 drop policy if exists "profiles own insert" on public.profiles;
 create policy "profiles own insert" on public.profiles for insert with check(auth.uid()=id and role='student');
 drop policy if exists "teacher profile update" on public.profiles;
 create policy "teacher profile update" on public.profiles for update using(public.is_teacher()) with check(public.is_teacher());

-- Courses
