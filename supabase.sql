-- تفعيل المدرس بدون كتابة الإيميل في SQL. كود التفعيل: TEACHER2026
create or replace function public.activate_teacher(p_code text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if p_code <> 'TEACHER2026' then
    raise exception 'كود تفعيل المدرس غير صحيح';
  end if;
  if auth.uid() is null then
    raise exception 'يجب تسجيل الدخول أولاً';
  end if;
  update public.profiles set role='teacher' where id=auth.uid();
  if not found then
    raise exception 'لم يتم العثور على ملف الحساب';
  end if;
end;
$$;

grant execute on function public.activate_teacher(text) to authenticated;

