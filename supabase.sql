create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'student' check(role in ('student','teacher','team')),
  student_code text unique,
  created_at timestamptz default now()
);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  price numeric(10,2) default 0,
  is_free boolean default false,
  created_at timestamptz default now()
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  title text not null,
  video_url text,
  pdf_path text,
  sort_order int default 0,
  created_at timestamptz default now()
);

create table if not exists public.enrollments (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  granted_by_code boolean default false,
  created_at timestamptz default now(),
  unique(student_id,course_id)
);

create table if not exists public.team_members (
  id bigint generated by default as identity primary key,
  name text not null,
  role_title text not null,
  permission text not null default 'support',
  icon text default '👤',
  created_at timestamptz default now()
);

alter table public.team_members add column if not exists icon text default '👤';

create table if not exists public.progress (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  completed boolean default false,
  updated_at timestamptz default now(),
  unique(student_id,lesson_id)
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name,student_code)
  values(new.id,coalesce(nullif(new.raw_user_meta_data->>'full_name',''),'طالب جديد'),nullif(new.raw_user_meta_data->>'student_code',''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_teacher()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='teacher');
$$;

