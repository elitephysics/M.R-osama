-- تخزين فيديوهات الدروس داخل Supabase Storage (Bucket خاص).
insert into storage.buckets (id, name, public)
values ('course-videos', 'course-videos', false)
on conflict (id) do update set public=false;

drop policy if exists "course videos teacher upload" on storage.objects;
create policy "course videos teacher upload"
on storage.objects for insert to authenticated
with check (bucket_id='course-videos' and public.is_teacher());

drop policy if exists "course videos teacher update" on storage.objects;
create policy "course videos teacher update"
on storage.objects for update to authenticated
using (bucket_id='course-videos' and public.is_teacher())
with check (bucket_id='course-videos' and public.is_teacher());

drop policy if exists "course videos teacher delete" on storage.objects;
create policy "course videos teacher delete"
on storage.objects for delete to authenticated
using (bucket_id='course-videos' and public.is_teacher());

drop policy if exists "course videos allowed read" on storage.objects;
create policy "course videos allowed read"
on storage.objects for select to authenticated
using (
  bucket_id='course-videos'
  and (
    public.is_teacher()
    or exists (
      select 1 from public.enrollments e
      where e.student_id=auth.uid()
        and e.course_id=split_part(name,'/',1)::bigint
    )
    or exists (
      select 1 from public.courses c
      where c.id=split_part(name,'/',1)::bigint
        and c.is_free=true
    )
  )
);
